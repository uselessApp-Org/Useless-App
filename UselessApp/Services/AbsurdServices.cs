    public static double Convert(double amount, string source, string target)
    {
        if (!double.IsFinite(amount) || amount < 0) throw new ArgumentOutOfRangeException(nameof(amount));
        var a=Units.FirstOrDefault(x=>x.Name.Equals(source,StringComparison.OrdinalIgnoreCase)) ?? throw new ArgumentException("Unknown input unit");
        var b=Units.FirstOrDefault(x=>x.Name.Equals(target,StringComparison.OrdinalIgnoreCase)) ?? throw new ArgumentException("Unknown output unit");
        if(a.Kind!=b.Kind) throw new ArgumentException("Length cannot be converted into mass");
        return amount*a.BaseValue/b.BaseValue;
    }
